def q(sql):
    """Run a query, return list of dicts (MySQL batch mode, tab separated)."""
    r = subprocess.run([MYSQL, "-u", "root", "-B", DB],
                       input=sql, stdout=subprocess.PIPE,
                       stderr=subprocess.STDOUT, text=True, check=True)
    lines = [l for l in r.stdout.strip().split("\n") if l]
    if not lines:
        return []
    head = lines[0].split("\t")
    rows = []
    for l in lines[1:]:
        vals = l.split("\t")
        rows.append({h: (None if v == "NULL" else v) for h, v in zip(head, vals)})
    return rows


def iso(dt):
    """'2026-01-12 13:30:00' -> '2026-01-12T13:30:00+02:00'"""
    return None if dt is None else dt.replace(" ", "T") + TZ


def money(v):
    """DECIMAL -> string. Never a float: 0.1+0.2 must not happen to money."""
    return None if v is None else str(Decimal(v).quantize(Decimal("0.01")))


