def _validate(obj, schema, defs, path=""):
    """Minimal draft-07 check covering types, enums, patterns and required.

    Not a full validator - just enough to catch the failure mode that actually
    happens here: the hand-authored definitions and the database-generated
    examples drifting apart after a schema change.
    """
    errs = []
    if "$ref" in schema:
        return _validate(obj, defs[schema["$ref"].split("/")[-1]], defs, path)
    if "oneOf" in schema:
        if not any(not _validate(obj, s, defs, path) for s in schema["oneOf"]):
            errs.append(f"{path}: matches none of oneOf")
        return errs
    t = schema.get("type")
    if t:
        types = t if isinstance(t, list) else [t]
        py = {"string": str, "integer": int, "number": (int, float),
              "boolean": bool, "object": dict, "array": list, "null": type(None)}
        if not any(isinstance(obj, py[x]) for x in types if x in py):
            return errs + [f"{path}: expected {types}, got {type(obj).__name__}"]
    if "enum" in schema and obj not in schema["enum"]:
        errs.append(f"{path}: {obj!r} not in enum")
    if "pattern" in schema and isinstance(obj, str):
        if not re.search(schema["pattern"], obj):
            errs.append(f"{path}: {obj!r} fails /{schema['pattern']}/")
    if isinstance(obj, dict):
        for r in schema.get("required", []):
            if r not in obj:
                errs.append(f"{path}.{r}: required but missing")
        for k, v in obj.items():
            if k.startswith("_"):
                continue
            ps = schema.get("properties", {}).get(k)
            if ps:
                errs += _validate(v, ps, defs, f"{path}.{k}")
    if isinstance(obj, list) and "items" in schema:
        for i, item in enumerate(obj):
            errs += _validate(item, schema["items"], defs, f"{path}[{i}]")
    return errs


def self_check(doc):
    """Validate the generated examples against the authored definitions."""
    defs, ex = doc["definitions"], doc["examples"]
    pairs = [("user_subscriber", "user"), ("user_merchant_till", "user"),
             ("transaction_category", "transaction_category"),
             ("tag", "tag"), ("system_log_orphan", "system_log")]
    errs = []
    for exname, defname in pairs:
        obj = {k: v for k, v in ex[exname].items() if not k.startswith("_")}
        errs += [f"{exname}: {m}" for m in _validate(obj, defs[defname], defs, exname)]
    for key in ("complete_transaction", "complete_transaction_flagged"):
        errs += [f"{key}: {m}" for m in
                 _validate(ex[key]["data"], defs["transaction"], defs, key)]
    return errs


